import { chromium } from "playwright";
import { fakeChain, fakeWallet, mockPage, registryLog, wallet } from "./fake-chain.mjs";
import { server } from "./harness.mjs";
const preview = await server();
const browser = await chromium.launch();
const context = await browser.newContext();
await fakeWallet(context);
const requestId = "0x" + "a1".repeat(32);
const fixture = fakeChain({ token: 1n, pending: [{ id: 801, requestId, questionHash: "0x" + "b1".repeat(32), requestedAt: 1792600000n, cleared: true }] });
fixture.state.verifiedEvents = [registryLog("Missed", { requestId, traitId: 801, reason: 8 }, { logIndex: "0x10" })];
const page = await context.newPage();
page.on("console", (m) => console.log("console", m.type(), m.text())); page.on("pageerror", (e) => console.log("pageerror", e.message));
await mockPage(page, fixture);
await page.goto(preview.url + "#/claim");
await page.getByText(/Dependencies verified/).waitFor();
await page.getByRole("button", { name: "Connect", exact: true }).first().click();
await page.getByRole("button", { name: "Browser wallet", exact: true }).click();
await page.waitForTimeout(8000);
console.log(await page.locator("#pick-801").innerText());
const counts = {}; for (const c of fixture.state.calls) counts[c.method] = (counts[c.method] || 0) + 1; console.log(counts);
